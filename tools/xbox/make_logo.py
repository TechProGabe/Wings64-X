#!/usr/bin/env python3
"""Wings64-X dashboard icon: a hang-glider silhouette on a dark round badge
with a glowing rim (transparent background).

  tools/xbox/make_logo.py <out.png> [size]

Drawn from scratch with Pillow shapes only (no fonts, game or console art), so
it can live in the repo. xbox/assets/logo.png is generated by this;
xbe_title_image.py turns it into the XBE's $$XTIMAGE and default.tbn.
"""
import math
import sys

from PIL import Image, ImageChops, ImageDraw, ImageFilter

S = 1024  # work size; downscaled at the end for smooth edges
C = S / 2


def poly_mask(pts):
    m = Image.new("L", (S, S), 0)
    ImageDraw.Draw(m).polygon(pts, fill=255)
    return m


def vgrad(top, bot, y0=0, y1=S):
    g = Image.new("RGBA", (S, S))
    d = ImageDraw.Draw(g)
    for y in range(S):
        t = min(1.0, max(0.0, (y - y0) / (y1 - y0)))
        d.line([(0, y), (S, y)], fill=tuple(int(a + (b - a) * t) for a, b in zip(top, bot)) + (255,))
    return g


def lerp(p, q, t):
    return (p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t)


def wing_points():
    """Delta wing seen from slightly below: a nose (apex) at the top, swept
    leading edges down to two wingtips, and a sagging trailing edge (a
    quadratic curve) joining the tips."""
    apex = (C, C - 300)
    lt, rt = (C - 400, C + 90), (C + 400, C + 90)
    ctrl = (C, C + 130)  # a shallow sag: the trailing edge stays nearly straight
    trail = []
    for i in range(1, 24):
        t = i / 24  # quadratic Bezier from the left tip to the right tip
        x = (1 - t) ** 2 * lt[0] + 2 * (1 - t) * t * ctrl[0] + t * t * rt[0]
        y = (1 - t) ** 2 * lt[1] + 2 * (1 - t) * t * ctrl[1] + t * t * rt[1]
        trail.append((x, y))
    return apex, lt, rt, trail


def main():
    out = sys.argv[1]
    size = int(sys.argv[2]) if len(sys.argv) > 2 else 256
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    r = 440
    sky = (126, 206, 255)

    # drop shadow under the badge
    sh = Image.new("L", (S, S), 0)
    ImageDraw.Draw(sh).ellipse((C - r, C - r + 18, C + r, C + r + 18), fill=150)
    img.paste(Image.new("RGBA", (S, S), (0, 0, 0, 255)), (0, 0), sh.filter(ImageFilter.GaussianBlur(16)))

    # glowing rim: a soft sky-blue halo just outside the steel rim
    halo = Image.new("L", (S, S), 0)
    ImageDraw.Draw(halo).ellipse((C - r - 20, C - r - 20, C + r + 20, C + r + 20), fill=230)
    halo = halo.filter(ImageFilter.GaussianBlur(14))
    img.paste(Image.new("RGBA", (S, S), sky + (255,)), (0, 0), halo.point(lambda v: v * 170 // 255))

    # badge: steel rim, then a deep blue-black face with a faint sky glow
    rim = Image.new("L", (S, S), 0)
    ImageDraw.Draw(rim).ellipse((C - r, C - r, C + r, C + r), fill=255)
    img.paste(vgrad((236, 240, 248), (96, 104, 122), C - r, C + r), (0, 0), rim)
    face_r = r - 30
    face = Image.new("L", (S, S), 0)
    ImageDraw.Draw(face).ellipse((C - face_r, C - face_r, C + face_r, C + face_r), fill=255)
    img.paste(vgrad((22, 34, 62), (6, 8, 18), C - face_r, C + face_r), (0, 0), face)
    glow = Image.new("L", (S, S), 0)
    ImageDraw.Draw(glow).ellipse((C - 320, C - 300, C + 320, C + 300), fill=120)
    glow = ImageChops.multiply(glow.filter(ImageFilter.GaussianBlur(100)), face)
    img.paste(Image.new("RGBA", (S, S), sky + (255,)), (0, 0), glow)

    apex, lt, rt, trail = wing_points()
    wing_pts = [apex, lt] + trail + [rt]
    wing = poly_mask(wing_pts)
    keel_end = (C, C + 150)  # where the keel meets the pilot's harness
    head = (C, C + 175)

    # pilot's cables: from the leading edges down to the harness
    cable_src_l = lerp(apex, lt, 0.42)
    cable_src_r = lerp(apex, rt, 0.42)
    dark = (10, 16, 30, 255)
    light = (240, 248, 255, 255)

    # dark outline for the whole glider (wing + cables + pilot), then the fills
    outline = wing.filter(ImageFilter.MaxFilter(21))
    d = ImageDraw.Draw(img)
    img.paste(Image.new("RGBA", (S, S), dark), (0, 0), outline)
    d.line([cable_src_l, keel_end], fill=dark, width=26)
    d.line([cable_src_r, keel_end], fill=dark, width=26)
    d.ellipse((head[0] - 44, head[1] - 44, head[0] + 44, head[1] + 44), fill=dark)
    d.rounded_rectangle((C - 56, C + 180, C + 56, C + 300), radius=34, fill=dark)

    # wing: a white-to-sky gradient body with a darker keel and rib lines
    img.paste(vgrad((255, 255, 255), (150, 208, 248), apex[1], lt[1] + 200), (0, 0), wing)
    d = ImageDraw.Draw(img)
    rib_col = (96, 160, 216, 255)
    for t in (0.2, 0.4, 0.6, 0.8):
        end = trail[int(t * (len(trail) - 1))]
        d.line([apex, end], fill=rib_col, width=5)
    d.line([apex, keel_end], fill=rib_col, width=8)

    # cables and pilot in light colour
    d.line([cable_src_l, keel_end], fill=light, width=12)
    d.line([cable_src_r, keel_end], fill=light, width=12)
    d.ellipse((head[0] - 34, head[1] - 34, head[0] + 34, head[1] + 34), fill=light)
    d.rounded_rectangle((C - 46, C + 186, C + 46, C + 290), radius=28, fill=light)

    # downscale: supersampled work image to the output size
    img.resize((size, size), Image.LANCZOS).save(out)
    print(f"wrote {out} ({size}x{size})")


if __name__ == "__main__":
    main()
