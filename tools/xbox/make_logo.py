#!/usr/bin/env python3
"""Wings64-X dashboard icon: a sky tile with a chunky italic "64", a striped
hang glider and a cloud above it, and a green "X" tag on the 4.

  tools/xbox/make_logo.py <out.png> [size]

A sibling of the wings64-dc logo (the maintainer's Dreamcast port): the same
sun-gradient lettering with a white and a navy rim and a navy drop shadow,
the same yellow/red striped glider, outlined clouds and a rounded tag, with
an Xbox-green tag saying "X" where the Dreamcast one says "DC". Drawn from
scratch with Pillow shapes only (no fonts, game or console art), so it can
live in the repo and is deterministic. xbox/assets/logo.png is generated by
this; xbe_title_image.py turns it into the XBE's $$XTIMAGE (128x128 DXT1,
1-bit alpha) and default.tbn. For DXT1 the silhouette is one opaque rounded
tile with a hard edge: no glow or shadow outside it.
"""
import math
import sys

from PIL import Image, ImageChops, ImageDraw, ImageFilter

S = 1024  # work size; downscaled at the end for smooth edges
C = S / 2

NAVY = (22, 32, 90)
WHITE = (255, 255, 255)
CLOUD_SHADE = (201, 227, 255)
SUN = [(0.0, (255, 243, 138)), (0.45, (255, 210, 63)), (1.0, (255, 138, 31))]
GREEN = [(0.0, (164, 230, 70)), (1.0, (40, 150, 30))]
SKY = [(0.0, (40, 140, 240)), (0.62, (150, 215, 255)), (0.63, (79, 179, 255)), (1.0, (31, 111, 224))]
SAIL, STRIPE = (255, 210, 63), (232, 64, 46)
SUIT, SKIN = (47, 125, 225), (255, 217, 176)


# --- masks -------------------------------------------------------------------

def mask():
    return Image.new("L", (S, S), 0)


def poly(pts):
    m = mask()
    ImageDraw.Draw(m).polygon([tuple(p) for p in pts], fill=255)
    return m


def ell(cx, cy, rx, ry=None):
    ry = rx if ry is None else ry
    m = mask()
    ImageDraw.Draw(m).ellipse((cx - rx, cy - ry, cx + rx, cy + ry), fill=255)
    return m


def rrect(x0, y0, x1, y1, r):
    m = mask()
    ImageDraw.Draw(m).rounded_rectangle((x0, y0, x1, y1), radius=int(r), fill=255)
    return m


def stroke(pts, w):
    """A polyline of width w with round joins and caps."""
    m = mask()
    d = ImageDraw.Draw(m)
    d.line([tuple(p) for p in pts], fill=255, width=int(w), joint="curve")
    for x, y in (pts[0], pts[-1]):
        d.ellipse((x - w / 2, y - w / 2, x + w / 2, y + w / 2), fill=255)
    return m


def union(*ms):
    out = ms[0]
    for m in ms[1:]:
        out = ImageChops.lighter(out, m)
    return out


def inter(a, b):
    return ImageChops.multiply(a, b)


def sub(a, b):
    return ImageChops.subtract(a, b)


def dilate(m, d):
    """Grow a mask by about d px with round corners (blur, then a low threshold)."""
    return m.filter(ImageFilter.GaussianBlur(d / 2.05)).point(lambda v: 255 if v > 6 else 0)


def offset(m, dx, dy):
    return m.transform(m.size, Image.AFFINE, (1, 0, -dx, 0, 1, -dy))


def shear(m, k, yb):
    """Italic: x moves right by k per px above the baseline yb."""
    return m.transform(m.size, Image.AFFINE, (1, k, -k * yb, 0, 1, 0), resample=Image.BICUBIC)


def vgrad(stops, y0, y1):
    g = Image.new("RGBA", (S, S))
    d = ImageDraw.Draw(g)
    for y in range(S):
        t = min(1.0, max(0.0, (y - y0) / (y1 - y0)))
        for (ta, ca), (tb, cb) in zip(stops, stops[1:]):
            if t <= tb or tb == stops[-1][0]:
                u = min(1.0, max(0.0, (t - ta) / (tb - ta)))
                col = tuple(int(a + (b - a) * u) for a, b in zip(ca, cb))
                break
        d.line([(0, y), (S, y)], fill=col + (255,))
    return g


def paint(img, src, m):
    if isinstance(src, tuple):
        src = Image.new("RGBA", (S, S), src + (255,))
    img.paste(src, (0, 0), m)


def xf(pts, cx, cy, s, ang):
    ca, sa = math.cos(math.radians(ang)), math.sin(math.radians(ang))
    return [(cx + s * (x * ca - y * sa), cy + s * (x * sa + y * ca)) for x, y in pts]


def bez(p0, p1, p2, n=24):
    return [((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0],
             (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1]) for t in (i / n for i in range(n + 1))]


# --- lettering: heavy rounded italic digits, built from strokes and discs -----

def glyph6(x0, y0, h):
    w, br = h * 0.27, h * 0.375  # stroke, bowl radius
    bcx, bcy = x0 + br, y0 + h - br
    bowl = sub(ell(bcx, bcy, br), ell(bcx + h * 0.01, bcy + h * 0.005, br - w))
    stem = stroke(bez((x0 + w / 2, bcy), (x0 + w / 2 - h * 0.02, y0 + w / 2), (x0 + br * 1.7, y0 + w / 2)), w)
    top = rrect(x0 + br * 0.9, y0, x0 + br * 1.9, y0 + w, w * 0.45)
    return union(bowl, stem, top), x0 + 2 * br


def glyph4(x0, y0, h):
    w = h * 0.28
    sx = x0 + h * 0.47  # stem's left edge
    bar_y = y0 + h * 0.58
    stem = rrect(sx, y0, sx + w, y0 + h, w * 0.4)
    bar = rrect(x0, bar_y, sx + w + h * 0.12, bar_y + w * 0.95, w * 0.4)
    dw = w * 0.8
    diag = stroke([(sx + w * 0.5, y0 + dw / 2), (x0 + dw / 2, bar_y + dw / 2)], dw)
    return union(stem, bar, diag), sx + w + h * 0.12


def glyph_x(cx, cy, h, w):
    a = h / 2 - w / 2
    return union(stroke([(cx - a, cy - a), (cx + a, cy + a)], w), stroke([(cx - a, cy + a), (cx + a, cy - a)], w))


def sixty_four(img, x0, y0, h):
    """Sun-gradient fill, white inner rim, navy outer rim and navy drop shadow."""
    m6, x1 = glyph6(x0, y0, h)
    m4, _ = glyph4(x1 + 10, y0, h)
    m = shear(union(m6, m4), 0.2, y0 + h)
    outer = dilate(m, 56)
    paint(img, NAVY, offset(outer, 14, 18))
    paint(img, NAVY, outer)
    paint(img, WHITE, dilate(m, 22))
    paint(img, vgrad(SUN, y0, y0 + h), m)


def x_tag(img, cx, cy, w, h, ang):
    """Rounded green tag, tilted, with a navy rim and shadow and a white X."""
    rim = 14
    box = mask()
    ImageDraw.Draw(box).rounded_rectangle((cx - w / 2 - rim, cy - h / 2 - rim, cx + w / 2 + rim, cy + h / 2 + rim),
                                          radius=int(h * 0.28 + rim), fill=255)
    face = mask()
    ImageDraw.Draw(face).rounded_rectangle((cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2), radius=int(h * 0.28), fill=255)
    box = box.rotate(ang, resample=Image.BICUBIC, center=(cx, cy))
    face = face.rotate(ang, resample=Image.BICUBIC, center=(cx, cy))
    paint(img, NAVY, offset(box, 10, 14))
    paint(img, NAVY, box)
    paint(img, vgrad(GREEN, cy - h / 2, cy + h / 2), face)
    x = glyph_x(cx - 3, cy + 2, h * 0.71, h * 0.245)
    paint(img, NAVY, dilate(x, 11))
    paint(img, WHITE, x)


# --- glider and cloud ---------------------------------------------------------

def glider(img, cx, cy, s, ang):
    """Hang glider seen from below-front: a swept delta sail striped yellow and
    red, keel, control bar and a small pilot; one navy rim around it all."""
    T = lambda pts: xf(pts, cx, cy, s, ang)
    sail_pts = T([(-120, 18), (0, -50), (120, 18), (0, 4)])
    sail = poly(sail_pts)
    stripes = union(*[poly(T(p)) for p in (
        [(-130, 30), (-60, -50), (-38, -50), (-108, 30)],
        [(-12, -60), (12, -60), (12, 30), (-12, 30)],
        [(38, -50), (60, -50), (130, 30), (108, 30)])])
    frame = union(stroke(T([(0, 4), (0, 30)]), 5 * s),
                  stroke(T([(-22, 44), (0, 30), (22, 44)]), 5 * s), stroke(T([(-24, 44), (24, 44)]), 6 * s))
    (bx, by), (hx, hy) = T([(0, 37), (0, 25)])
    body, head = ell(bx, by, 7 * s, 10 * s), ell(hx, hy, 6.5 * s)
    paint(img, NAVY, dilate(union(sail, frame, body, head), 4.5 * s))
    paint(img, SAIL, sail)
    paint(img, STRIPE, inter(stripes, sail))
    paint(img, NAVY, frame)
    for part, col in ((body, SUIT), (head, SKIN)):
        paint(img, NAVY, dilate(part, 1.6 * s))
        paint(img, col, part)


def cloud_mask(cx, cy, s):
    m = rrect(cx - 1.25 * s, cy - 0.1 * s, cx + 1.25 * s, cy + 0.42 * s, 0.26 * s)
    for x, y, r in ((-0.9, 0.1, 0.42), (-0.4, -0.25, 0.55), (0.25, -0.35, 0.62), (0.85, 0.0, 0.45)):
        m = union(m, ell(cx + x * s, cy + y * s, r * s))
    return m


def cloud(img, cx, cy, s):
    m = cloud_mask(cx, cy, s)
    paint(img, NAVY, dilate(m, 6))
    paint(img, WHITE, m)
    paint(img, CLOUD_SHADE, sub(m, cloud_mask(cx, cy - s * 0.12, s)))


# --- the icon -----------------------------------------------------------------

def main():
    out = sys.argv[1]
    size = int(sys.argv[2]) if len(sys.argv) > 2 else 256
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))

    # the tile: navy border, sky over a sea band
    tile = rrect(30, 30, S - 30, S - 30, 150)
    face = rrect(58, 58, S - 58, S - 58, 122)
    paint(img, NAVY, tile)
    paint(img, vgrad(SKY, 58, S - 58), face)

    # everything inside, clipped to the sky
    art = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    cloud(art, 230, 230, 80)
    sixty_four(art, 130, 390, 430)
    x_tag(art, 808, 808, 200, 180, 6)
    glider(art, 590, 222, 2.75, -11)
    img.paste(art, (0, 0), inter(art.getchannel("A"), face))

    img.resize((size, size), Image.LANCZOS).save(out)
    print(f"wrote {out} ({size}x{size})")


if __name__ == "__main__":
    main()
